//! dss-host: orchestrator between a llama.cpp model and the CPU DSS kernel.
//!
//! Modes (how the tool call is formed):
//!   intent : (default) the model emits only " [INTENT: CHECK_IS_DSS]" (or CARD_FROM_SUM,
//!            NEXT_GREEDY, CHECK_BOUND). The host parses the integers from
//!            the prompt with a strict per-task parser, checks that the
//!            intent names the prompt's own task, and runs the kernel.
//!            Generation stops right after the intent; the kernel result is
//!            returned verbatim as the final answer (the model never copies
//!            it). A missing, malformed or wrong-task intent, or a rejected
//!            prompt, returns an explicit "ERROR: ..." and no answer.
//!   intent-gen : as intent, but the model writes the final answer after
//!            reading the result (the round-5 behaviour).
//!   args   : the model emits " <call>TOOL ARGS</call>" and the host runs the
//!            kernel on the model's arguments (copy errors possible).
//!   gbnf   : as args, but the call is generated by llama-completion under a
//!            GBNF grammar that only allows a tool name plus integers.
//! The host then appends " <result>RESULT</result>" and lets the model write
//! the final answer (one line). There is no GPU on this box; the kernel is
//! plain CPU Rust.
//!
//! Usage:
//!   dss-host run   --mode M --gguf G [--bin DIR] "PROMPT"
//!   dss-host eval  --mode M --gguf G [--bin DIR] PROMPTS.txt OUT.tsv
//!   dss-host answer            (stdin: prompts; kernel answer per line, no model)
//!   dss-host kernel            (stdin: "isdss 1 2 4" | "card 1 2 4 sum 3" |
//!                               "next 3 5 6" | "bound 12 60" per line)
mod kernel;
mod parse;
mod phi;

use parse::{parse_call, parse_prompt, Task};
use std::io::{BufRead, Write};
use std::process::Command;

fn run_task(t: &Task) -> Option<String> {
    match t {
        Task::IsDss(s) => Some(kernel::tool_isdss(s)),
        Task::Card(w, s) => kernel::tool_card(w, *s),
        Task::Next(s) => kernel::tool_next(s),
        Task::Bound(k, a) => Some(kernel::tool_bound(*k, *a)),
        Task::PhiNormalize(ts) => phi::normalize(ts).ok().map(|x| x.fmt()),
        Task::PhiMul(x, y) => x.mul(*y).ok().map(|z| z.fmt()),
        Task::PhiConj(x) => x.conj().ok().map(|z| z.fmt()),
        Task::PhiNorm(x) => x.norm().ok().map(|z| z.to_string()),
    }
}

struct Llama { bin: String, gguf: String }

const GRAMMAR: &str = r#"root ::= " <call>" body "</call>"
body ::= ("isdss" | "next") ints | "card" ints " sum " int | "bound " int " " int
ints ::= (" " int)+
int ::= [1-9] [0-9]*
"#;

impl Llama {
    /// Greedy continuation of `text` (llama-simple), with the prompt stripped.
    fn simple(&self, text: &str, n: usize) -> Result<String, String> {
        let out = Command::new(format!("{}/llama-simple", self.bin))
            .args(["-m", &self.gguf, "-n", &n.to_string(), text])
            .output().map_err(|e| e.to_string())?;
        let s = String::from_utf8_lossy(&out.stdout).to_string();
        s.strip_prefix(text).map(|x| x.to_string()).ok_or_else(|| "llama-simple did not echo prompt".into())
    }

    /// Greedy grammar-constrained continuation (llama-completion --grammar-file).
    fn grammar(&self, text: &str, n: usize) -> Result<String, String> {
        let gpath = std::env::temp_dir().join("dss-host-call.gbnf");
        std::fs::write(&gpath, GRAMMAR).map_err(|e| e.to_string())?;
        let out = Command::new(format!("{}/llama-completion", self.bin))
            .args(["-m", &self.gguf, "-n", &n.to_string(), "--temp", "0", "-no-cnv",
                   "--no-display-prompt", "--grammar-file", gpath.to_str().unwrap(), "-p", text])
            .output().map_err(|e| e.to_string())?;
        let s = String::from_utf8_lossy(&out.stdout).to_string();
        Ok(s.replace(" [end of text]", "").trim_end_matches('\n').to_string())
    }
}

struct Outcome { call: String, wellformed: bool, correct_tool: bool, copy_error: bool,
                 result: String, final_: String, text: String, note: String }

fn first_line(s: &str) -> &str { s.split('\n').next().unwrap_or("") }

fn rollout(llm: &Llama, mode: &str, prompt: &str) -> Outcome {
    let mut o = Outcome { call: String::new(), wellformed: false, correct_tool: false, copy_error: false,
                          result: String::new(), final_: String::new(), text: prompt.to_string(), note: String::new() };
    let task = match parse_prompt(prompt) {
        Ok(t) => t,
        Err(e) => { o.note = format!("prompt rejected: {e}"); return o; }
    };
    let gen = match mode {
        "gbnf" => llm.grammar(prompt, 40),
        "intent" | "intent-gen" => llm.simple(prompt, 16),
        _ => llm.simple(prompt, 40),
    };
    let gen = match gen { Ok(g) => g, Err(e) => { o.note = e; return o; } };
    let line = first_line(&gen);
    let intent_mode = mode == "intent" || mode == "intent-gen";
    let (call, bound_task) = if intent_mode {
        let Some(end) = line.find(']') else { o.call = line.into(); o.note = "no intent".into(); return o; };
        let call = &line[..=end];
        let want = format!(" [INTENT: {}]", task.intent());
        if call == want { (call.to_string(), Some(task.clone())) } else { (call.to_string(), None) }
    } else {
        let Some(end) = line.find("</call>") else { o.call = line.into(); o.note = "no </call>".into(); return o; };
        let call = &line[..end + "</call>".len()];
        let body = call.strip_prefix(" <call>").and_then(|c| c.strip_suffix("</call>"));
        (call.to_string(), body.and_then(|b| parse_call(b).ok()))
    };
    o.call = call.clone();
    let Some(t) = bound_task else { o.note = "malformed or wrong-task call".into(); return o; };
    let Some(res) = run_task(&t) else { o.note = "kernel rejected arguments".into(); return o; };
    o.wellformed = true;
    o.correct_tool = t == task;
    o.copy_error = t.tool() == task.tool() && t != task;
    if mode == "intent" {
        // Host-side answer: the kernel result is the final answer.
        o.final_ = res.clone();
        o.text = format!("{prompt}{call} <result>{res}</result> {res}");
        o.result = res;
        return o;
    }
    let text = format!("{prompt}{call} <result>{res}</result>");
    let fin = llm.simple(&text, 24).unwrap_or_default();
    o.final_ = first_line(&fin).to_string();
    o.text = format!("{text}{}", o.final_);
    o.result = res;
    o
}

fn esc(s: &str) -> String { s.replace('\t', "\\t").replace('\n', "\\n") }

fn arg(args: &[String], k: &str, default: &str) -> String {
    args.iter().position(|a| a == k).and_then(|i| args.get(i + 1)).cloned().unwrap_or(default.into())
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let cmd = args.get(1).map(|s| s.as_str()).unwrap_or("");
    let llm = Llama { bin: arg(&args, "--bin", "/workspace/llama.cpp/build/bin"), gguf: arg(&args, "--gguf", "") };
    let mode = arg(&args, "--mode", "intent");
    let pos: Vec<&String> = {
        let mut v = vec![]; let mut i = 2;
        while i < args.len() { if args[i].starts_with("--") { i += 2 } else { v.push(&args[i]); i += 1 } }
        v
    };
    match cmd {
        "run" => {
            let o = rollout(&llm, &mode, pos[0]);
            if o.wellformed { println!("{}", o.text); } else { println!("ERROR: {} (model emitted {:?})", o.note, o.call); }
        }
        "eval" => {
            let f = std::fs::File::open(pos[0]).expect("prompts file");
            let mut out = std::fs::File::create(pos[1]).expect("out file");
            writeln!(out, "prompt\tcall\twellformed\tcorrect_tool\tcopy_error\tresult\tfinal\ttext\tnote").unwrap();
            for line in std::io::BufReader::new(f).lines() {
                let p = line.unwrap();
                let o = rollout(&llm, &mode, &p);
                writeln!(out, "{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}", esc(&p), esc(&o.call), o.wellformed as u8,
                         o.correct_tool as u8, o.copy_error as u8, esc(&o.result), esc(&o.final_), esc(&o.text),
                         esc(&o.note)).unwrap();
            }
        }
        "answer" => {
            // Kernel only (no model): prompt per line -> result or ERROR.
            for line in std::io::stdin().lock().lines() {
                let l = line.unwrap();
                match parse_prompt(&l) {
                    Ok(t) => println!("{}", run_task(&t).unwrap_or_else(|| "ERROR: kernel rejected arguments".into())),
                    Err(e) => println!("ERROR: prompt rejected: {e}"),
                }
            }
        }
        "kernel" => {
            for line in std::io::stdin().lock().lines() {
                let l = line.unwrap();
                let r = parse_call(&l).ok().and_then(|t| run_task(&t)).unwrap_or_else(|| "ERR".into());
                println!("{r}");
            }
        }
        _ => { eprintln!("usage: dss-host run|eval|kernel (see src/main.rs)"); std::process::exit(2); }
    }
}
